	setting: 'setting',
	/** Setting descriptors and the idiom reference (§3.1). */
	settingFile: 'setting/setting.md',
	/** Per-vault profile override; author edits win over the shipped profile. */
	idiom: 'setting/idiom.md',
	/** Unscoped formulas, reachable from every system. */
	formulas: 'setting/formulas.md',
	/** The clock binding: raw seconds, a Gregorian epoch, or a custom calendar. */
