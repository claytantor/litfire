/**
 * Where a directory used to live, and where its contents belong now.
 *
 * Read, never written. A vault written before `corpus/` and `setting/` keeps
 * loading exactly as it did — the loader walks both, the canonical page wins a
 * clash, and `/lint` reports the old location so the vault empties rather than
 * staying half-moved forever. This is the same contract `situations/inbox/`
 * has had since D19; the layout change simply made it apply to everything.
 */
export const LEGACY_DIRECTORIES: Readonly<Record<string, string>> = {
	characters: VAULT.characters,
	themes: VAULT.themes,
	places: VAULT.places,
	factions: VAULT.factions,
	artifacts: VAULT.artifacts,
	situations: VAULT.situations,
	'situations/inbox': VAULT.situations,
	systems: VAULT.systems,
	'timeline/moments': VAULT.moments,
	'timeline/arcs': VAULT.arcs,
	chapters: VAULT.chapters,
	system: VAULT.setting,
};

/**
 * Files from a layout litfire has moved on from, still read so no vault breaks.
 *
 * Each has a modern equivalent that is now the only thing written. Naming them
 * here lets `/lint` report a vault that still has one without the checks having
 * to know how the loader works.
 */
export const LEGACY_FILES: Readonly<Record<string, string>> = {
	'system/stats.md': 'corpus/systems/<id>.md',
	'system/skills.md': 'corpus/systems/<id>.md',
	'system/curves.md': 'corpus/systems/<id>.md',
	'system/system.md': VAULT.settingFile,
	'system/idiom.md': VAULT.idiom,
	'system/formulas.md': VAULT.formulas,
	'timeline/world-events.md': 'corpus/moments/<id>.md',
	'timeline/time.md': VAULT.time,
};

/**
 * Every directory a kind's pages may be sitting in, canonical home first.
 *
 * Order is the contract: the first file to claim an id wins, so a page already
 * moved beats the copy left behind. Lives here rather than in the loader
 * because the loader is not the only thing that has to find a page — the wiki
 * reads author prose straight off disk, and a reader that knows only the
 * canonical home renders an empty page for every vault that has not migrated.
 */
export function homesOf(canonical: string): string[] {
	return [
		canonical,
		...Object.entries(LEGACY_DIRECTORIES)
			.filter(([, to]) => to === canonical)
			.map(([from]) => from),
	];
}

export function resolve(root: string, ...segments: string[]): string {
	return path.join(root, ...segments);
}
